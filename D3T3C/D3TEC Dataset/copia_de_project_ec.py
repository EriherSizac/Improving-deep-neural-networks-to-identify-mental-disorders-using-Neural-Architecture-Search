def build_tf_model_from_dict(model_dict, input_shape=(128, 128, 3), verbose=False):
    """
    Construye un modelo de TensorFlow a partir de un diccionario de arquitectura, sin usar clases personalizadas.

    Tipos de capas soportadas:
      - 'Conv2D', 'DepthwiseConv2D', 'BatchNorm', 'MaxPooling',
        'Flatten', 'Dense', 'Dropout', 'DontCare', 'SelfAttention'

    Args:
        model_dict: diccionario con la definición de capas.
        input_shape: forma de la entrada (altura, anchura, canales).
        verbose: si True, muestra mensajes de depuración.

    Retorna:
        Un objeto tf.keras.Model.
    """
    inputs = tf.keras.Input(shape=input_shape)
    x = inputs

    # Conversión de canales si es necesario: si la entrada no tiene 4 canales, se ajusta.
    target_in_channels = 4
    if input_shape[-1] != target_in_channels:
        if verbose:
            print(f"Insertando capa de conversión: de {input_shape[-1]} a {target_in_channels} canales.")
        x = tf.keras.layers.Conv2D(target_in_channels, kernel_size=1, padding='same')(x)

    # Recorrer las capas del diccionario
    for layer in model_dict['layers']:
        if layer['type'] == 'Conv2D':
            x = tf.keras.layers.Conv2D(filters=layer['filters'],
                                       kernel_size=3,
                                       strides=layer['strides'],
                                       padding='same')(x)
            if layer['activation'].lower() == "relu":
                x = tf.keras.layers.ReLU()(x)
            else:
                x = tf.keras.layers.LeakyReLU()(x)

        elif layer['type'] == 'DepthwiseConv2D':
            x = tf.keras.layers.DepthwiseConv2D(kernel_size=3,
                                                strides=layer['strides'],
                                                padding='same')(x)
            x = tf.keras.layers.Activation(layer['activation'])(x)

        elif layer['type'] == 'BatchNorm':
            x = tf.keras.layers.BatchNormalization()(x)

        elif layer['type'] == 'MaxPooling':
            x = tf.keras.layers.MaxPooling2D(pool_size=2,
                                             strides=layer['strides'],
                                             padding='same')(x)

        elif layer['type'] == 'Flatten':
            x = tf.keras.layers.Flatten()(x)

        elif layer['type'] == 'Dense':
            x = tf.keras.layers.Dense(units=layer['units'],
                                      activation=layer['activation'])(x)

        elif layer['type'] == 'Dropout':
            x = tf.keras.layers.Dropout(rate=layer['rate'])(x)

        elif layer['type'] == 'DontCare':
            x = tf.identity(x)

        elif layer['type'] == 'SelfAttention':
            desired_filters = layer['filters']
            # Ajustar canales si es necesario.
            if x.shape[-1] != desired_filters:
                if verbose:
                    print(f"Ajustando canales en SelfAttention: {x.shape[-1]} -> {desired_filters}")
                x = tf.keras.layers.Conv2D(filters=desired_filters,
                                           kernel_size=1,
                                           padding='same')(x)
            window_size = layer.get('window_size', 16)
            attention_heads = layer.get('attention_heads', 4)
            # Uso de Lambda con argumento output_shape para evitar el error.
            x = tf.keras.layers.Lambda(
                lambda t: self_attention_block(t, filters=desired_filters,
                                               window_size=window_size,
                                               attention_heads=attention_heads,
                                               verbose=verbose),
                output_shape=lambda s: (s[0], s[1], s[2], desired_filters)
            )(x)
        else:
            if verbose:
                print(f"Tipo de capa desconocido: {layer['type']}. Se omite.")

    model = tf.keras.Model(inputs=inputs, outputs=x)
    return model

