def es(target_func, mu=10, lamb=1, F=2, rp=0.5, gens=100, n=10, auto_adapt=False, exp=0, resume=False):
    """
    Parámetros:
      - target_func: función objetivo.
      - mu: tamaño de la población.
      - lamb: número de hijos por generación.
      - F: factor de mutación.
      - rp: tasa de recombinación.
      - gens: número total de generaciones.
      - n: ventana para adaptar F (si auto_adapt True).
      - auto_adapt: flag para la adaptación de F.
      - exp: número de experimento (para identificar los checkpoints).
      - resume: bandera que indica si se desea reanudar desde un checkpoint previo.

    La función guarda, cada 100 generaciones, un checkpoint con todo el estado
    del algoritmo en la ruta:
      /content/drive/MyDrive/NAS/surr_m_4_ec/checkpoints/[exp]_[gen].pkl

    Además, al finalizar el experimento se guarda un checkpoint final (exp_final.pkl)
    con los arrays necesarios para graficar.
    """

    # Ruta de la carpeta para guardar los checkpoints en Google Drive
    checkpoint_dir = "/content/drive/MyDrive/NAS/surr_m_4_ec/checkpoints_r2"
    os.makedirs(checkpoint_dir, exist_ok=True)

    # Si se desea reanudar, se busca el último checkpoint para este experimento.
    if resume:
        checkpoint_pattern = os.path.join(checkpoint_dir, f"{exp}_*.pkl")
        checkpoint_files = glob.glob(checkpoint_pattern)
        if checkpoint_files:
            # Se selecciona el checkpoint con la mayor generación
            latest_checkpoint = max(checkpoint_files, key=lambda x: int(x.split('_')[-1].split('.')[0]) if x.split('_')[-1].split('.')[0].isdigit() else -1)
            print("Reanudando desde el checkpoint:", latest_checkpoint)
            with open(latest_checkpoint, "rb") as f:
                state = pickle.load(f)
            start_gen = state.get("current_generation", -1) + 1
            pop = state["population"]
            best_fitness_per_gen = state["best_fitness_per_gen"]
            Fs = state["Fs"]
            F = state["F"]
            succ_m_count = state["succ_m_count"]
        else:
            # Si no se encuentra ningún checkpoint, se inicia el experimento normalmente.
            print("No se encontró checkpoint, iniciando nuevo experimento.")
            start_gen = 0
            pop = pop_gen(mu)
            best_fitness_per_gen = []
            Fs = []
            succ_m_count = 0
    else:
        start_gen = 0
        pop = pop_gen(mu)
        best_fitness_per_gen = []
        Fs = []
        succ_m_count = 0

    # Barra de progreso desde la generación inicial hasta gens
    with tqdm(total=gens - start_gen, desc="Generaciones", initial=start_gen, leave=True) as pbar_gens:
        for gen in range(start_gen, gens):
            children = []

            # Evaluar la población actual y obtener el mejor individuo
            pop = [{'individual': parent['individual'], 'fitness': target_func(parent['individual'])} for parent in pop]
            best_parent = max(pop, key=lambda x: x['fitness'])

            for i in range(lamb):
                parent = pop[i]['individual']

                # Mapear el individuo a valores reales
                parent_unit = convert_individual(parent)
                best_parent_c = convert_individual(best_parent['individual'])

                # Mecanismo de mutación y reparación
                x2, x3 = random.sample(pop, 2)
                x2 = convert_individual(x2['individual'])
                x3 = convert_individual(x3['individual'])
                u = []
                for j in range(len(best_parent_c)):
                    u.append(best_parent_c[j] + F * (x2[j] - x3[j]))
                u = fixArch(convert_individual(u, to_real=False))
                u = convert_individual(u)

                # Operador de recombinación
                cr_points = get_cr_points(rp, len(parent))
                child = [u[j] if j in cr_points else parent[j] for j in range(len(u))]
                child = fixArch(convert_individual(child, to_real=False))

                children.append({'individual': child, 'fitness': 0})

            # Calcular fitness para cada hijo
            children = [{'individual': child['individual'], 'fitness': target_func(child['individual'])} for child in children]

            # Combinar la población actual y la descendencia
            complete_pop = pop + children

            if auto_adapt:
                # Contar mutaciones exitosas
                succ_m_count += get_succ_m(pop, children)

                # Adaptar F cada n generaciones
                if (gen + 1) % n == 0:
                    Fs.append(F)
                    ps = succ_m_count / (n * lamb)
                    if ps > 1/5:
                        F /= 0.817
                    elif ps < 1/5:
                        F *= 0.817
                    succ_m_count = 0

            # Seleccionar los mejores mu individuos para la siguiente generación
            pop = sorted(complete_pop, key=lambda x: x['fitness'], reverse=True)[:mu]
            best_fitness_per_gen.append(max(pop, key=lambda x: x['fitness'])['fitness'])

            # Guardar checkpoint cada 100 generaciones o al final del experimento
            if (gen + 1) % 100 == 0 or (gen == gens - 1):
                checkpoint_state = {
                    "current_generation": gen,
                    "population": pop,
                    "best_fitness_per_gen": best_fitness_per_gen,
                    "Fs": Fs,
                    "F": F,
                    "succ_m_count": succ_m_count
                }
                checkpoint_filename = os.path.join(checkpoint_dir, f"{exp}_{gen}.pkl")
                with open(checkpoint_filename, "wb") as f_checkpoint:
                    pickle.dump(checkpoint_state, f_checkpoint)

            pbar_gens.update(1)

    best_element = max(pop, key=lambda x: x['fitness'])
    Fs.append(F)

    # Guardar checkpoint final con el resumen del experimento para graficar
    final_state = {
        "best_element": best_element,
        "best_fitness_per_gen": best_fitness_per_gen,
        "Fs": Fs
    }
    final_checkpoint_filename = os.path.join(checkpoint_dir, f"{exp}_final.pkl")
    with open(final_checkpoint_filename, "wb") as f_final:
        pickle.dump(final_state, f_final)

    return best_element, best_fitness_per_gen, Fs

